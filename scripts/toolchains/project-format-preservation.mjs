import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { assertNodeVersion, repositoryRoot } from "./toolchain.mjs";

export function preservedFormattingPlan(root = repositoryRoot) {
  const preservation = JSON.parse(
    readFileSync(
      resolve(
        root,
        "scripts/toolchains/nextra-stable-docs/acceptance-inputs/preservation.json",
      ),
      "utf8",
    ),
  );
  const paths = [
    ...preservation.routes,
    ...preservation.examples,
    ...preservation.publicBoundarySources,
  ].map(({ path }) => {
    if (
      !path ||
      path.startsWith("/") ||
      path.includes("\\") ||
      path.split("/").includes("..")
    )
      throw new Error("Invalid canonical preservation input path");
    return "/" + path.replaceAll("[", "\\[").replaceAll("]", "\\]");
  });
  return [
    "# Generated by scripts/toolchains/project-format-preservation.mjs.",
    "# These bytes remain checked by the owning source-preservation contracts.",
    "CHANGELOG.md",
    "/.nx/workspace-data",
    ".build/",
    "dist/",
    ".next/",
    "build/",
    "",
    "# Retained upstream source and fixed acceptance/regression inputs.",
    "scripts/toolchains/**/canonical-source/",
    "scripts/toolchains/**/acceptance-inputs/",
    "scripts/toolchains/**/regression-inputs/",
    "scripts/toolchains/**/source-overlays/",
    "",
    "# Exact first-party inputs captured by the Nextra migration contract.",
    ...[...new Set(paths)].sort(),
    "",
  ].join("\n");
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  assertNodeVersion();
  if (
    process.argv.length !== 3 ||
    !["--check", "--write"].includes(process.argv[2])
  )
    throw new Error("Usage: project-format-preservation.mjs --check|--write");
  const path = resolve(repositoryRoot, ".prettierignore");
  const expected = preservedFormattingPlan();
  if (process.argv[2] === "--write") writeFileSync(path, expected);
  else if (readFileSync(path, "utf8").replaceAll("\r\n", "\n") !== expected)
    throw new Error(
      "Formatter preservation exclusions differ from their canonical input",
    );
}
